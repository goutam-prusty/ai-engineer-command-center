export function getClassificationForWeek(item: ResourceItem, week: number): ResourceClassification {
  if (item.weekClassifications && item.weekClassifications[week]) {
    return item.weekClassifications[week];
  }
  return item.defaultClassification;
}

export function getResourcesForWeek(week: number): ResourceItem[] {
  const rank: Record<ResourceClassification, number> = {
    ESSENTIAL: 0,
    OPTIONAL: 1,
    SKIP: 2,
  };
  return ALL_RESOURCES.filter((r) => r.mappedWeeks.includes(week)).sort((a, b) => {
    const classDiff = rank[getClassificationForWeek(a, week)] - rank[getClassificationForWeek(b, week)];
    if (classDiff !== 0) return classDiff;
    return a.priorityTier - b.priorityTier;
  });
}

